    g.add(cyl('Y', (0.0, 0.1850, hz + 0.0370), 0.00060, 0.0004, 10), 'reticle', 'body', 0.0, flat=True)
    g.add(box((0.0, 0.0900, 0.0145), (0.0100, 0.0560, 0.0120)), 'steel', 'bolt', 0.0006)
