def build_bullpup():
    purge('WpnBullpup')
    g = G('WpnBullpup')
    PL, SD, AL = 'polymer', 'steel_dark', 'alu_dark'
    side = [(0.0, -0.062), (0.0, 0.030), (0.090, 0.040), (0.300, 0.040), (0.420, 0.034), (0.470, 0.030), (0.470, -0.034), (0.345, -0.040), (0.322, -0.046), (0.300, -0.050), (0.205, -0.050), (0.172, -0.046), (0.110, -0.044)]
    shell = extrude(side, 'YZ', -0.0255, 0.0255)
    shell = cut(shell, box((0.0245, 0.0950, 0.0140), (0.0180, 0.0560, 0.0200)), box((0.0, 0.1925, -0.040), (0.0262, 0.0490, 0.0480)))
