    g.add(extrude([(0.0, -0.062), (0.0, 0.030), (-0.013, 0.027), (-0.013, -0.058)], 'YZ', -0.0235, 0.0235), 'rubber', 'body', 0.0012)
    for i in range(7):
        g.add(box((0.0, -0.0140, -0.050 + i * 0.0108), (0.0400, 0.0012, 0.0022)), 'rubber', 'body', 0.0003)
    g.add(rail(0.100, 0.468, 0.0520, support=0.0390), AL, 'body', 0.0004)
    g.add(extrude([(0.340, -0.040), (0.470, -0.034), (0.470, -0.020), (0.340, -0.030)], 'YZ', -0.0285, 0.0285), PL, 'body', 0.0012)
    for i in range(5):
        g.add(box((0.0, 0.362 + i * 0.020, -0.0405), (0.0360, 0.0060, 0.0016)), PL, 'body', 0.0004)
    g.add(cyl('Y', (0.0, 0.5600, 0.0), 0.0078, 0.2400, 20), SD, 'body', 0.0)
    g.add(tube(0.468, 0.500, 0.0185, 0.0090, 28, 0.0, 0.0), SD, 'body', 0.0006)
    fh = lathe([(0.630, 0.0090), (0.634, 0.0112), (0.668, 0.0112), (0.676, 0.0098), (0.676, 0.0058), (0.630, 0.0058)], 'Y', (0, 0, 0), 24, closed=True)
    fh = cut(fh, *[radial_slot(0.654, a, 0.0028, 0.030, 0.0040, 0.0140) for a in (0, 90, 180, 270)])
    g.add(fh, SD, 'body', 0.0006)
    gp = lambda i: (0.268 - 0.024 * i / 7, -0.040 - 0.110 * i / 7)
    g.add(loft_path([gp(i) for i in range(8)], lambda i: rrect(0.0340 * (1 + 0.06 * math.sin(math.pi * i / 7)), 0.0420, 0.0100, 3)), PL, 'body', 0.0012)
    g.add(ribbon([(0.3080, -0.0450), (0.3100, -0.0640), (0.2950, -0.0750), (0.2750, -0.0750), (0.2600, -0.0620), (0.2540, -0.0450)], 0.0036, -0.0060, 0.0060), PL, 'body', 0.0008)
    g.add(cyl('X', (-0.0255, 0.2120, -0.0200), 0.0045, 0.0060, 16), SD, 'body', 0.0004)
    hx0, hx1, hz = 0.1500, 0.2100, 0.0505
    hs = extrude([(hx0, hz), (hx1, hz), (hx1 - 0.004, hz + 0.0480), (hx0 + 0.004, hz + 0.0480)], 'YZ', -0.0180, 0.0180)
    hs = cut(hs, box((0.0, (hx0 + hx1) / 2, hz + 0.0370), (0.0245, 0.0900, 0.0150)))
    g.add(hs, AL, 'body', 0.0008)
    for yy in (hx0 + 0.0025, hx1 - 0.0025):
        g.add(cut(box((0.0, yy, hz + 0.0370), (0.0290, 0.0030, 0.0220)), box((0.0, yy, hz + 0.0370), (0.0245, 0.0100, 0.0150))), SD, 'body', 0.0004)
    ring_pts = [Vector((0.0045 * math.cos(2 * math.pi * i / 28), 0.0, hz + 0.0370 + 0.0045 * math.sin(2 * math.pi * i / 28))) for i in range(29)]
