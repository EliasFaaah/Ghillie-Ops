    g.add(cyl('X', (-0.0270, 0.1750, 0.0230), 0.0040, 0.0120, 14), SD, 'charging_handle', 0.0004)
    g.add(cyl('X', (-0.0345, 0.1750, 0.0230), 0.0078, 0.0050, 18), SD, 'charging_handle', 0.0006)
    g.pivots['charging_handle'] = (-0.0270, 0.1750, 0.0230)
    g.add(extrude([(0.2760, -0.0100), (0.2820, -0.0100), (0.2850, -0.0360), (0.2900, -0.0540), (0.2830, -0.0570), (0.2780, -0.0400)], 'YZ', -0.0030, 0.0030), 'steel', 'trigger', 0.0004)
    g.pivots['trigger'] = (0.2800, -0.0120, 0.0)
    mp = arc_path((0.1925, -0.0400), (0.1925, -0.1900), 0.0450, 11)
    g.add(loft_path(mp, lambda i: rrect(0.0228 if i < 11 else 0.0250, 0.0452 if i < 11 else 0.0500, 0.0045, 2)), PL, 'magazine', 0.0010)
    g.pivots['magazine'] = (0.0, 0.1925, -0.0400)
